bool MatchesSymbolName(std::string_view normalized,
                      const ConditionLanguageSymbol &symbol) {
    if (symbol.canonicalName == normalized) return true;
    return std::find(symbol.aliases.begin(), symbol.aliases.end(), normalized) !=
            symbol.aliases.end();
}

const ConditionLanguageSymbol *FindConditionSymbol(std::string_view name) {
    const std::string normalized = Lower(name);
    for (const ConditionLanguageSymbol &symbol : GetConditionSymbols()) {
        if (MatchesSymbolName(normalized, symbol)) return &symbol;
    }
    return nullptr;
}

const ConditionLanguageConstant *FindConditionConstant(
        std::string_view name) {
    const std::string normalized = Lower(name);
    for (const ConditionLanguageConstant &constant :
         GetConditionConstants()) {
        if (constant.canonicalName == normalized) return &constant;
        if (std::find(constant.aliases.begin(), constant.aliases.end(),
                      normalized) != constant.aliases.end()) {
            return &constant;
        }
    }
    return nullptr;
}

const ConditionLanguageFunction *FindConditionFunction(std::string_view name) {
    const std::string normalized = Lower(name);
    for (const ConditionLanguageFunction &function : GetConditionFunctions()) {
        if (function.canonicalName == normalized) return &function;
        if (std::find(function.aliases.begin(), function.aliases.end(),
                      normalized) != function.aliases.end()) {
            return &function;
        }
    }
    return nullptr;
}

std::optional<ConditionLanguageSymbolResolution> ResolveConditionSymbol(
        std::string_view name) {
    const auto *const symbol = FindConditionSymbol(name);
    if (symbol == nullptr || symbol->external) return std::nullopt;
    return ConditionLanguageSymbolResolution{symbol, symbol->sourceValue,
                                           symbol->sourceComponent};
}

