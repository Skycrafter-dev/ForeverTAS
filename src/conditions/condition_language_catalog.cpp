ConditionLanguageFunction MakeFunction(
        std::string_view canonicalName,
        std::vector<std::string_view> aliases,
        std::string_view friendlyName,
        std::string_view category,
        std::string_view signature,
        std::string_view returnType,
        std::string_view documentation,
        std::string_view insertionTemplate,
        std::string_view example,
        ConditionLanguageFunctionKind kind,
        bool pointTargetOnly = false) {
    std::vector<ConditionLanguageValueType> parameterTypes;
    ConditionLanguageValueType resultType =
            ConditionLanguageValueType::Scalar;
    switch (kind) {
    case ConditionLanguageFunctionKind::KmH:
    case ConditionLanguageFunctionKind::Deg:
    case ConditionLanguageFunctionKind::TimeSince:
        parameterTypes = {ConditionLanguageValueType::Scalar};
        break;
    case ConditionLanguageFunctionKind::Distance:
        parameterTypes = {ConditionLanguageValueType::Vector,
                          ConditionLanguageValueType::Vector};
        break;
    case ConditionLanguageFunctionKind::VariableLookup:
        parameterTypes = {ConditionLanguageValueType::ExternalName};
        resultType = ConditionLanguageValueType::Dynamic;
        break;
    }
    return {canonicalName,
            std::move(aliases),
            friendlyName,
            category,
            signature,
            returnType,
            documentation,
            insertionTemplate,
            example,
            kind,
            pointTargetOnly,
            std::move(parameterTypes),
            resultType};
}

